using System.Net;
using System.Net.NetworkInformation;
using System.Text.Json;

namespace HappBox;
public sealed partial class MainForm
{
    private readonly InternetIncident _internetIncident = new();
    private long _lastIncidentLogSample;
    private long _lastIncidentNativeLogSample;
    private bool _agMonitorRunning;
    private readonly CancellationTokenSource _incidentLifetime = new();
    private CancellationTokenSource _incidentStopCancellation = new();
    private void CancelInternetIncidentOnStop()
    {
        var previous = _incidentStopCancellation;
        _incidentStopCancellation = new();
        previous.Cancel(); previous.Dispose();
    }
    private void DeliverNativeIncidentLogs(string? summary, string? line, long queuedAt)
    {
        var delay = System.Diagnostics.Stopwatch.GetElapsedTime(queuedAt).TotalMilliseconds;
        var watch = System.Diagnostics.Stopwatch.StartNew();
        if (summary is not null) Log(summary);
        if (line is not null) Log(line);
        if (delay >= 50 || watch.ElapsedMilliseconds >= 50 || Environment.TickCount64 - _lastIncidentNativeLogSample >= 5000)
        {
            _lastIncidentNativeLogSample = Environment.TickCount64;
            _internetIncident.Observe("native_log_delivery_completed", watch.ElapsedMilliseconds, queueDelayMs: (long)delay);
        }
    }
    private void InitializeInternetIncident()
    {
        if (!AgDnsEnabled) return;
        NetworkAddressChangedEventHandler address = (_, _) => _internetIncident.Observe("network_address_changed");
        NetworkAvailabilityChangedEventHandler available = (_, e) => _internetIncident.Observe(e.IsAvailable ? "network_available" : "network_unavailable");
        NetworkChange.NetworkAddressChanged += address;
        NetworkChange.NetworkAvailabilityChanged += available;
        Disposed += (_, _) => { _incidentLifetime.Cancel(); _incidentStopCancellation.Cancel(); _incidentStopCancellation.Dispose(); NetworkChange.NetworkAddressChanged -= address; NetworkChange.NetworkAvailabilityChanged -= available; };
    }
    private async Task<object> MarkInternetIncidentAsync()
    {
        if (!AgDnsEnabled) throw new InvalidOperationException("Эта диагностика предназначена для Windows 10.");
        var active = IsConnectionRunning();
        var ready = _connectedAt is not null;
        var tun = _state.TunEnabled;
        var engine = _state.RunningCore.ToString();
        var protocol = _state.RunningProfileSnapshot?.Protocol.ToString();
        var resolverText = _state.DnsServer;
        var ag = _agDns?.Status ?? "notRequired";
        var udp443Setting = _state.RealityUdp443Enabled;
        var profileFlow = _state.RunningProfileSnapshot?.Flow;
        var buildId = _state.RunningCore == CoreKind.IorCore ? CoreEngineService.NativeBuildId(_state) : null;
        var runId = _connectionDiagnostics?.RunId;
        var adapter = _state.RunningCore == CoreKind.XrayCore ? "ior-xray" : runId is { Length: 32 } ? "ior-native-" + runId[..8] : "";
        // Native TUN name is generated by the host, never accept an arbitrary adapter from the UI.
        var owned = NetworkInterface.GetAllNetworkInterfaces().Where(n => n.Name == adapter).ToArray();
        var recent = _logs.Where(l => l.Contains("HYSTERIA2_TRANSPORT_METRICS") || l.Contains("HYSTERIA2_UDP_QUEUE_METRICS")).TakeLast(120)
            .Concat(_logs.Where(l => l.Contains("[IOR:warning]") || l.Contains("[IOR:error]")).TakeLast(50)).ToArray();
        var generation = Interlocked.Read(ref _processLogGeneration);
        using var lifetime = CancellationTokenSource.CreateLinkedTokenSource(_backgroundConnectionCancellation.Token, _incidentLifetime.Token, _incidentStopCancellation.Token);
        var id = await _internetIncident.CaptureAsync(Path.Combine(_appDir, "diagnostics", "internet-incidents"), async token =>
        {
            var checks = new List<Task<InternetIncident.Probe>>();
            checks.Add(InternetIncident.MeasureAsync("network_snapshot", async ct => await InternetIncident.ReadNetworkAsync(ct), token, 8000));
            if (active && ready && tun)
            {
                checks.Add(InternetIncident.MeasureAsync("system_dns", async ct =>
                {
                    var addresses = await Dns.GetHostAddressesAsync("www.youtube.com", ct);
                    return "addressCount=" + addresses.Length + ";mayUseSystemCache=true";
                }, token));
                var own = owned.SingleOrDefault(n => n.Name == adapter);
                IPAddress? dns = null;
                try { dns = own?.GetIPProperties().DnsAddresses.FirstOrDefault(); }
                catch (NetworkInformationException) { checks.Add(Task.FromResult(new InternetIncident.Probe("tun_dns", "unavailable", 0, "AdapterChangedDuringInspection"))); }
                if (dns is not null) checks.Add(InternetIncident.MeasureAsync("tun_dns", ct => InternetIncident.DnsAsync(dns, "www.youtube.com", ct), token));
                if (IPAddress.TryParse(resolverText, out var resolver) && PhysicalInterfaceResolver.UsesInterfaceForAddress(resolver, adapter))
                    checks.Add(InternetIncident.MeasureAsync("configured_resolver_udp", ct => InternetIncident.DnsAsync(resolver, "www.youtube.com", ct), token));
                checks.Add(InternetIncident.MeasureAsync("youtube_https_tcp", ct => InternetIncident.HttpsAsync(false, adapter, ct), token));
                checks.Add(InternetIncident.MeasureAsync("youtube_http3_udp443", ct => InternetIncident.HttpsAsync(true, adapter, ct), token));
            }
            var results = await Task.WhenAll(checks);
            var interfaces = InternetIncident.Interfaces();
            return new { windows = Environment.OSVersion.Version.ToString(), appVersion = AppVersion, buildId, active, ready, tun, engine, protocol, adapter, ag, udp443Setting,
                explicitUdp443 = profileFlow == "xtls-rprx-vision-udp443",
                generation, currentGeneration = Interlocked.Read(ref _processLogGeneration), connectionChanged = generation != Interlocked.Read(ref _processLogGeneration),
                configuredResolver = resolverText, interfaces, results, recent = recent.Select(l => ConnectionDiagnostics.Redact(l, DiagnosticSecrets())).ToArray() };
        }, lifetime.Token);
        if (id is null) return new { busy = true };
        Log("INTERNET_INCIDENT_SAVED: отметка проблемы сохранена; VPN не перезапускался. Экспорт содержит локальные сведения о сети.");
        return new { id, busy = false };
    }
}
