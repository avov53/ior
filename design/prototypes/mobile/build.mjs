import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {rolldown} from '../../node_modules/rolldown/dist/index.mjs';
import {browserComponents} from '../desktop-refresh/ui-components.mjs';
const root=new URL('./',import.meta.url);
const read=name=>readFile(new URL(name,root),'utf8');
const controls=await read('controls.js');
const transitions=await read('transitions.js');
const aurora=await read('aurora.js');
const ambient=await read('ambient.js');
const features=await read('app-routing.js');
const softLists=await read('soft-lists.js');
const script=(await read('mobile.js')).replace('/*__MOBILE_TRANSITIONS__*/',()=>features+'\n'+controls+'\n'+transitions+'\n'+aurora+'\n'+ambient+'\n'+softLists);
new Function(script);
const css=await read('mobile.css')+'\n'+await read('linear.css')+'\n'+await read('controls.css')+'\n'+await read('aurora.css')+'\n'+await read('ambient.css')+'\n'+await read('app-routing.css')+'\n'+await read('soft-lists.css');
const flags=Object.fromEntries(await Promise.all(['nl','fi','de'].map(async code=>[code,'data:image/svg+xml;base64,'+(await readFile(new URL('../../node_modules/flag-icons/flags/4x3/'+code+'.svg',root))).toString('base64')])));
const build=await rolldown({input:fileURLToPath(new URL('runtime-entry.js',root))});
const result=await build.generate({format:'iife',minify:true});await build.close();
let html=await read('source.html');
html=html.replace('<link rel="stylesheet" href="mobile.css">',()=>'<style>'+css+'</style>').replace('<script src="mobile.js"></script>',()=>'<script>'+ ('window.mobileFlags='+JSON.stringify(flags)+';'+browserComponents()+result.output[0].code+script).replaceAll('</script>','<\\/script>')+'</script>');
const licenses=await readFile(new URL('../desktop-refresh/LICENSE-lucide.txt',root),'utf8')+'\n'+await readFile(new URL('../desktop-refresh/LICENSE-qrcode.txt',root),'utf8')+'\n'+await readFile(new URL('../../node_modules/flag-icons/LICENSE',root),'utf8')+'\n'+await readFile(new URL('../../node_modules/motion/LICENSE.md',root),'utf8');
html=html.replace('</head>',()=>'<script type="text/plain" id="licenses">'+licenses.replaceAll('</script>','<\\/script>')+'</script></head>');
await writeFile(new URL('index.html',root),html);console.log('Mobile prototype built. Desktop files unchanged.');
